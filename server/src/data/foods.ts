export const FOOD_SOURCES = ["中国食物成分表（第6版）", "中国居民膳食指南（2022）"];

/**
 * 按名称查食物。匹配顺序：完全同名 → 别名完全命中 → 名称互相包含（取较长者优先）。
 * 返回 null 表示表中没有，调用方应用 CATEGORY_FALLBACK 兜底并标注为估算。
 */
export function findFood(rawName: string): FoodItem | null {
  const name = String(rawName || "").trim();
  if (!name) return null;

  const exact = FOODS.find((f) => f.name === name);
  if (exact) return exact;

  const byAlias = FOODS.find((f) => f.alias.some((a) => a === name));
  if (byAlias) return byAlias;

  // 包含匹配：如「红烧排骨」含「排骨」、「清蒸鲈鱼」含「鲈鱼」
  let best: { food: FoodItem; len: number } | null = null;
  for (const f of FOODS) {
    const keys = [f.name, ...f.alias];
    for (const k of keys) {
      if (k.length < 2) continue;
      if (name.includes(k) || k.includes(name)) {
        if (!best || k.length > best.len) best = { food: f, len: k.length };
      }
    }
  }
  return best ? best.food : null;
}

/** 中文数字 */
const CN_NUM: Record<string, number> = {
  一: 1, 二: 2, 两: 2, 三: 3, 四: 4, 五: 5, 六: 6, 七: 7, 八: 8, 九: 9, 十: 10, 半: 0.5,
};

/** 可重复的份量单位：一个、两碗、三片…… */
const COUNT_UNITS = "碗盘份杯勺个只条根块片把包罐餐口";

/**
 * 把模型给的份量文本换算成克数。
 *
 * 这里的优先级是有讲究的，踩过两个坑：
 * 1) 最初让 PORTION_UNITS 的固定值优先，导致「一个鸡蛋」按「一个=100g」算成 100g，
 *    而一个鸡蛋实际 50g，一餐热量直接虚高 70 kcal。
 * 2) 同一套固定值还把「一份红烧肉」按「一份=200g」算，实际一份红烧肉约 150g，
 *    热量虚高 235 kcal。
 * 所以纯量词要优先用食物自己的 defaultPortion，固定值只作为查不到食物时的兜底。
 */
export function portionToGrams(portion: string | undefined, food: FoodItem | null): { grams: number; assumed: boolean } {
  const p = String(portion || "").trim().replace(/\s+/g, "");
  if (p) {
    // 1) 明确克数：200g / 180克 / 0.25公斤
    const g = p.match(/(\d+(?:\.\d+)?)(g|克|公克|kg|公斤)/i);
    if (g) {
      const n = Number(g[1]);
      const isKg = /kg|公斤/i.test(g[2]);
      return { grams: Math.round(isKg ? n * 1000 : n), assumed: false };
    }

    // 2) 斤 / 两：中文数字与阿拉伯数字都要认（「一两」= 50g，不是 200g）
    const jin = p.match(/^(半|[一二两三四五六七八九十]|\d+(?:\.\d+)?)斤$/);
    if (jin) {
      const n = CN_NUM[jin[1]] ?? Number(jin[1]);
      return { grams: Math.round(n * 500), assumed: false };
    }
    const liang = p.match(/^(半|[一二两三四五六七八九十]|\d+(?:\.\d+)?)两$/);
    if (liang) {
      const n = CN_NUM[liang[1]] ?? Number(liang[1]);
      return { grams: Math.round(n * 50), assumed: false };
    }

    // 3) 中文/阿拉伯数字 + 量词：两个、三片、2碗
    const counted = p.match(new RegExp(`^(半|[一二两三四五六七八九十]|\\d+(?:\\.\\d+)?)(${[...COUNT_UNITS].join("|")})$`));
    if (counted) {
      const n = CN_NUM[counted[1]] ?? Number(counted[1]);
      const unit = counted[2];
      if (food) return { grams: Math.round(food.defaultPortion.grams * n), assumed: false };
      const base = PORTION_UNITS["一" + unit] ?? 200;
      return { grams: Math.round(base * n), assumed: true };
    }

    // 4) 带大小修饰的份量：一小碗、一大盘、半份（固定值比默认份量更贴切）
    if (PORTION_UNITS[p]) return { grams: PORTION_UNITS[p], assumed: false };
    for (const [k, v] of Object.entries(PORTION_UNITS)) {
      // 只在存在「小/大/半」这类修饰时才走这条，避免「一碗」被固定值覆盖
      if (/[小大半个]/.test(k) && p.includes(k)) return { grams: v, assumed: false };
    }

    // 5) 纯量词：一碗 / 一个 / 一份 / 一杯 → 优先用食物自身份量
    const bare = p.replace(/^一/, "");
    if ([...COUNT_UNITS].includes(bare)) {
      if (food) return { grams: food.defaultPortion.grams, assumed: false };
      return { grams: PORTION_UNITS["一" + bare] ?? 200, assumed: true };
    }

    // 6) 其他描述（「几口」「一小把」等）走包含匹配
    for (const [k, v] of Object.entries(PORTION_UNITS)) {
      if (p.includes(k)) return { grams: v, assumed: false };
    }
  }
  if (food) return { grams: food.defaultPortion.grams, assumed: true };
  return { grams: 200, assumed: true };
}
