/**
 * 常见食物营养表（每 100g 可食部）
 *
 * 用途：把视觉模型识别出的「食物名 + 份量」换算成热量与营养素。
 *
 * 为什么热量不交给模型算：
 * 模型能大致认出「这是一盘番茄炒蛋」，但它报出的热量经常错 2-3 倍——
 * 同一盘菜，它会给出 120 kcal 也可能给 400 kcal，且每次不一样。
 * 而食物成分表是测出来的固定值。「识别交给模型、计算交给数据」，
 * 才能保证你今天问和明天问，同一种食物得到同一个数字。
 *
 * 数据来源：《中国食物成分表（第6版）》《中国居民膳食指南（2022）》
 * 成品菜（dish 类）为家常做法估算值，油盐用量差异较大，仅供参考。
 *
 * 注意：per100 是「每 100 克」而非「每份」，份量换算见 defaultPortion。
 */

export type FoodCategory =
  | "staple"    // 主食
  | "meat"      // 畜肉
  | "poultry"   // 禽肉
  | "seafood"   // 水产
  | "egg"       // 蛋类
  | "dairy"     // 奶类
  | "soy"       // 豆制品
  | "vegetable" // 蔬菜
  | "mushroom"  // 菌藻
  | "fruit"     // 水果
  | "nut"       // 坚果
  | "oil"       // 油脂
  | "drink"     // 饮品
  | "dish"      // 成品菜
  | "snack";    // 零食点心

export interface FoodItem {
  id: string;
  name: string;
  /** 常见叫法、简称、错别字写法，用于模糊匹配 */
  alias: string[];
  category: FoodCategory;
  /** 每 100g 可食部 */
  per100: { kcal: number; protein: number; carb: number; fat: number };
  /** 钠 mg / 100g */
  sodiumPer100: number;
  /** 默认一份的克数（模型没给份量时使用） */
  defaultPortion: { label: string; grams: number };
}

