/**
 * 检索。做法是「原句直接子串匹配」，不做滑窗分词。
 *
 * 为什么放弃分词：最初用 2–4 字滑窗切词再双向匹配，结果「今天天气不错适合出去
 * 玩吗」这种闲聊会命中「水」「一天」之类的碎片关键词，被塞进两条营养条文。
 * 这比检索不到更糟——模型会拿不相关的条文硬凑一句"依据《指南》"。
 *
 * 现在的取舍是：宁可漏召回，也不误召回。漏了就让模型用通用常识回答（安全降级），
 * 错了就是"假装有依据"（危险）。
 */
export function searchGuidelines(query: string, limit = 3): GuidelineSnippet[] {
  const q = String(query || "").toLowerCase();
  if (q.trim().length < 2) return [];

  const scored = GUIDELINES.map((g) => {
    let score = 0;
    for (const k of g.keywords) {
      const kk = k.toLowerCase();
      if (!kk) continue;
      if (q.includes(kk)) score += kk.length >= 2 ? 3 : 2;
    }
    return { g, score };
  })
    .filter((x) => x.score >= 2)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit);

  return scored.map((x) => x.g);
}

/** 整理成给模型读的文本，明确告知这是本系统内置条文，可放心引用 */
export function guidelinesToText(snippets: GuidelineSnippet[]): string {
  if (!snippets.length) return "";
  const body = snippets
    .map((s) => `《${s.topic}》${s.title}\n${s.body}\n出处：${s.source}`)
    .join("\n\n");
  return `【可引用的指南条文（本系统内置，引用时标注出处即可，不要编造其他条文）】\n${body}`;
}
