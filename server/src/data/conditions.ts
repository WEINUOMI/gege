/** 按名称精确匹配（前端传上来的就是这些中文字符串） */
export function findCondition(name: string): ConditionRule | undefined {
  return CONDITIONS.find((c) => c.name === name || name.includes(c.name) || c.name.includes(name));
}

/**
 * 把病史整理成给模型的结构化文本。
 * 只输出用户实际勾选的病史，避免模型泛泛堆砌所有疾病注意事项。
 */
export function conditionsToText(names: string[]): string {
  const rules = (names || []).map(findCondition).filter((x): x is ConditionRule => !!x);
  if (!rules.length) return "";
  const blocks = rules.map((r) => {
    const focus = r.dietFocus.map((x) => `  · ${x}`).join("\n");
    const limit = r.dietLimit.map((x) => `  · ${x}`).join("\n");
    const ex = r.exerciseNote.map((x) => `  · ${x}`).join("\n");
    const mon = r.monitor.join("、");
    return `${r.name}（依据 ${r.source}）\n饮食宜：\n${focus}\n饮食忌：\n${limit}\n运动注意：\n${ex}\n需监测：${mon}`;
  });
  return `【用户病史对应的饮食与运动约束（系统已按指南整理，优先遵守）】\n${blocks.join("\n\n")}`;
}
